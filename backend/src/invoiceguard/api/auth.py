"""Who is calling, and what they may do.

Three things resolve to a Principal:

* A signed-in session (prefix "igs_"): a person who logged in with an email and password.
  The browser holds the token; only its hash is stored, and ending the session revokes it.

* Reviewer keys from the API_KEYS environment variable ("key:name" pairs). They are people
  working in the review UI and carry the human scopes. A name listed in ADMIN_USERS also
  gets the admin scope.
* Keys issued through the admin API (prefix "ig_"), stored only as a SHA-256 hash. These
  are the keys given to agents and integrations. An agent can never hold review or admin
  scope, so it cannot approve or reject anything: a person decides, an agent proposes.

The name recorded in the audit log always comes from the key, never from a request body.
"""

import base64
import hashlib
import hmac
import secrets
import uuid
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta

from fastapi import Depends, Header, HTTPException
from sqlalchemy import select, update
from sqlalchemy.orm import Session

from invoiceguard.api.deps import get_session
from invoiceguard.config import settings
from invoiceguard.db import models as m

KEY_PREFIX = "ig_"  # an API key, for an agent or integration
SESSION_PREFIX = "igs_"  # a signed-in session, for a person

# What each scope allows.
#   read     see cases, documents, metrics and packs
#   submit   upload a document or submit structured data
#   propose  record a suggested decision (changes no state)
#   review   approve, reject, edit, replay: the decisions that belong to a person
#   post     post an approved case to the system of record (an agent also needs a grant)
#   admin    manage principals
SCOPES = frozenset({"read", "submit", "propose", "review", "post", "admin"})
HUMAN_SCOPES = frozenset({"read", "submit", "review", "post"})
AGENT_SCOPES = frozenset({"read", "submit", "propose", "post"})
_TOUCH_EVERY = timedelta(minutes=5)


@dataclass(frozen=True)
class Principal:
    name: str
    kind: str  # "human" or "agent"
    scopes: frozenset[str]
    packs: tuple[str, ...] = ()
    user_id: uuid.UUID | None = None  # set when the caller is a signed-in person
    email: str | None = None

    def can(self, scope: str) -> bool:
        return scope in self.scopes


def all_pack_ids() -> tuple[str, ...]:
    from invoiceguard.packs.registry import list_packs

    return tuple(p.id for p in list_packs())


def key_scopes_for(owner_scopes: frozenset[str] | set[str]) -> frozenset[str]:
    """What a key generated by a person may do at most: what they may do, plus suggesting
    (an agent-only scope any reader may hand out). Never review or admin."""
    allowed = set(owner_scopes) & AGENT_SCOPES
    if "read" in owner_scopes:
        allowed.add("propose")
    return frozenset(allowed)


def hash_key(key: str) -> str:
    return hashlib.sha256(key.encode()).hexdigest()


# Passwords are hashed with scrypt (standard library) and a random salt per password.
_SCRYPT = {"n": 2**14, "r": 8, "p": 1}


def hash_password(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode(), salt=salt, dklen=32, **_SCRYPT)
    return "scrypt${}${}${}${}${}".format(
        _SCRYPT["n"],
        _SCRYPT["r"],
        _SCRYPT["p"],
        base64.b64encode(salt).decode(),
        base64.b64encode(digest).decode(),
    )


# Checked when the email is unknown, so a missing account takes as long as a wrong password.
_DUMMY_HASH = hash_password(secrets.token_urlsafe(16))


def verify_password(password: str, stored: str) -> bool:
    try:
        scheme, n, r, p, salt, digest = stored.split("$")
        if scheme != "scrypt":
            return False
        candidate = hashlib.scrypt(
            password.encode(),
            salt=base64.b64decode(salt),
            dklen=32,
            n=int(n),
            r=int(r),
            p=int(p),
        )
        return hmac.compare_digest(candidate, base64.b64decode(digest))
    except (ValueError, TypeError):
        return False


def new_session_token() -> str:
    return SESSION_PREFIX + secrets.token_urlsafe(32)


def new_key() -> str:
    """A fresh key. Shown once at creation; only its hash is kept."""
    return KEY_PREFIX + secrets.token_urlsafe(32)


def parse_api_keys(raw: str) -> dict[str, str]:
    users: dict[str, str] = {}
    for pair in raw.split(","):
        key, sep, name = pair.strip().partition(":")
        if sep and key and name:
            users[key] = name
    return users


def _admin_names() -> set[str]:
    return {n.strip() for n in settings.admin_users.split(",") if n.strip()}


def _from_environment(key: str) -> Principal | None:
    for known, name in parse_api_keys(settings.api_keys).items():
        if secrets.compare_digest(known, key):
            scopes = HUMAN_SCOPES | ({"admin"} if name in _admin_names() else set())
            return Principal(
                name=name, kind="human", scopes=frozenset(scopes), packs=all_pack_ids()
            )
    return None


def _from_database(session: Session, key: str) -> Principal | None:
    if not key.startswith(KEY_PREFIX):
        return None
    row = session.scalar(select(m.Principal).where(m.Principal.key_hash == hash_key(key)))
    if row is None or row.disabled:
        return None
    scopes = frozenset(row.scopes)
    if row.owner_id is not None:
        owner = session.get(m.User, row.owner_id)
        if owner is None or owner.disabled:
            return None  # a person's keys stop working when their account does
        scopes &= key_scopes_for(owner.scopes)  # and never exceed what the person may do
    now = datetime.now(UTC)
    if row.last_used_at is None or now - row.last_used_at > _TOUCH_EVERY:
        session.execute(
            update(m.Principal).where(m.Principal.id == row.id).values(last_used_at=now)
        )
    return Principal(name=row.name, kind=row.kind, scopes=scopes, packs=tuple(row.packs))


def designated_admin_emails() -> set[str]:
    return {e.strip().lower() for e in settings.admin_emails.split(",") if e.strip()}


def _from_session(session: Session, token: str) -> Principal | None:
    if not token.startswith(SESSION_PREFIX):
        return None
    row = session.scalar(
        select(m.UserSession).where(m.UserSession.token_hash == hash_key(token))
    )
    if row is None or row.revoked or row.expires_at <= datetime.now(UTC):
        return None
    user = session.get(m.User, row.user_id)
    if user is None or user.disabled:
        return None
    # An email named in ADMIN_EMAILS is an administrator whenever the setting is present,
    # whatever order things were set up in.
    admin = user.is_admin or user.email in designated_admin_emails()
    scopes = frozenset(user.scopes) | ({"admin"} if admin else frozenset())
    return Principal(
        name=user.name,
        kind="human",
        scopes=scopes,
        packs=tuple(user.packs),
        user_id=user.id,
        email=user.email,
    )


def presented_key(x_api_key: str | None, authorization: str | None) -> str | None:
    """The key from X-API-Key, or from 'Authorization: Bearer' (what MCP clients send)."""
    if x_api_key:
        return x_api_key
    if authorization and authorization.lower().startswith("bearer "):
        return authorization[7:].strip() or None
    return None


def authenticate(session: Session, key: str | None) -> Principal | None:
    if not key:
        return None
    return (
        _from_environment(key) or _from_database(session, key) or _from_session(session, key)
    )


def current_principal(
    x_api_key: str | None = Header(default=None),
    authorization: str | None = Header(default=None),
    session: Session = Depends(get_session),
) -> Principal:
    principal = authenticate(session, presented_key(x_api_key, authorization))
    if principal is None:
        raise HTTPException(status_code=401, detail="invalid or missing API key")
    return principal


def current_user(principal: Principal = Depends(current_principal)) -> str:
    """The name actions are recorded under."""
    return principal.name


def require_scope(scope: str):
    """Dependency that refuses the request unless the caller holds the scope."""

    def check(principal: Principal = Depends(current_principal)) -> Principal:
        if not principal.can(scope):
            raise HTTPException(status_code=403, detail=f"this key does not have the {scope} scope")
        return principal

    return check
